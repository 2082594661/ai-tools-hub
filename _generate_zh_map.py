def build():
    s2t_char = {}
    for pair in CHAR_PAIRS:
        # 跳过无意义的 X X 自我映射（len!=2 或 简==繁）
        if len(pair) == 2 and pair[0] != pair[1]:
            s2t_char[pair[0]] = pair[1]
    s2t_word = {}
    for i in range(0, len(WORD_PAIRS), 2):
        if i + 1 < len(WORD_PAIRS):
            s2t_word[WORD_PAIRS[i]] = WORD_PAIRS[i+1]
    # 反转生成繁→简 + 专用繁→简对（T2S_EXTRA 每个元素是"繁简"两字对）
    t2s_char = {v: k for k, v in s2t_char.items()}
    for pair in T2S_EXTRA:
        if len(pair) == 2:
            t2s_char[pair[0]] = pair[1]
    t2s_word = {v: k for k, v in s2t_word.items()}

    js = """/* zh-map.js — 简繁转换映射表（常用差异字 + 常用消歧词组，约 {c} 字 {w} 词）
 * 由 _generate_zh_map.py 生成，转换逻辑见 tools-v2.js 的 initZhConvert
 */
window.ZH_MAP = {{
  s2tChar: {s2t_char_json},
  s2tWord: {s2t_word_json},
  t2sChar: {t2s_char_json},
  t2sWord: {t2s_word_json}
}};
"""
    out = js.format(
        c=len(s2t_char), w=len(s2t_word),
        s2t_char_json=json.dumps(s2t_char, ensure_ascii=False, sort_keys=True),
        s2t_word_json=json.dumps(s2t_word, ensure_ascii=False, sort_keys=True),
        t2s_char_json=json.dumps(t2s_char, ensure_ascii=False, sort_keys=True),
        t2s_word_json=json.dumps(t2s_word, ensure_ascii=False, sort_keys=True),
    )
    path = os.path.join(ROOT, "assets", "js", "zh-map.js")
    with io.open(path, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"✓ zh-map.js 生成: {len(s2t_char)} 单字对, {len(s2t_word)} 词组对, {len(out)} bytes")

if __name__ == "__main__":
    build()
